/** Route overrides live with the global language metadata, not in competing effects. */
export function applyDocumentMetadata(language: Language, pathname: string): void {
  const base = documentCopy[language];
  const contact = pathname === "/contact" || pathname === "/contact/" ? contactCopy[language] : undefined;
  const plus = pathname === "/plus" || pathname === "/plus/";
  const pricing = pathname === "/pricing" || pathname === "/pricing/";
  const metadata = contact ? { ...base, title: `${contact.title} — Sajda`, description: contact.lead }
    : plus ? { ...base, title: "Sajda Trading — Lost Domains", description: language === "sv"
      ? "En källbaserad arbetsyta för upptäckta domäner. Granska registerstatus, belägg och risker innan nästa beslut."
      : "An evidence-led workspace for discovered domains. Review registry status, sources and risks before your next decision." }
    : pricing ? { ...base, title: language === "sv" ? "Priser & nivåer — Sajda" : "Pricing & plans — Sajda", description: language === "sv"
      ? "Jämför Gratis, Bas, Premium och Trading. Tydliga månadspriser i USD och aktuell information om funktioner och åtkomst."
      : "Compare Free, Bas, Premium and Trading. Clear monthly USD prices and current feature and access information." }
    : base;
  document.documentElement.lang = metadata.htmlLang;
  document.title = metadata.title;
  for (const selector of ["meta[name='description']", "meta[property='og:description']", "meta[name='twitter:description']"]) {
    document.querySelector(selector)?.setAttribute("content", metadata.description);
  }
  for (const selector of ["meta[property='og:title']", "meta[name='twitter:title']"]) {
    document.querySelector(selector)?.setAttribute("content", metadata.title);
  }
  document.querySelector("meta[property='og:locale']")?.setAttribute("content", metadata.ogLocale);
}

function interpolate(template: string, values?: TemplateValues): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function translate(language: Language, key: TranslationKey, values?: TemplateValues): string {
  return interpolate(translatedMessages[language][key], values);
}

interface LanguageContextValue {
  language: Language;
  selectedLanguage: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: TemplateValues) => string;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function getStoredLanguage(): Language {
  if (typeof window === "undefined") return "en";
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === "sv" || stored === "es" || stored === "fr" || stored === "zh" ? stored : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [selectedLanguage, setSelectedLanguage] = useState<Language>(getStoredLanguage);
  const language = selectedLanguage;

  useEffect(() => {
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, selectedLanguage);
    } catch {
      // The interface still works when private browsing blocks storage.
    }
    applyDocumentMetadata(selectedLanguage, window.location.pathname);
  }, [selectedLanguage]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    selectedLanguage,
    setLanguage: setSelectedLanguage,
    t: (key, values) => translate(selectedLanguage, key, values),
  }), [language, selectedLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within a LanguageProvider");
  return context;
}
