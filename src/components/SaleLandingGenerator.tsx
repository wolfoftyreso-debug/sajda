const localeByLanguage: Record<Language, string> = {
  en: "en-US",
  sv: "sv-SE",
  es: "es-ES",
  fr: "fr-FR",
  zh: "zh-CN",
};

/** Escapes dynamic content before it is inserted into the downloadable HTML document. */
// Exported for standalone sale-page validation; it is deliberately not a React component.
// eslint-disable-next-line react-refresh/only-export-components
export function escapeSaleLandingHtml(value: string | number) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/**
 * A downloadable page is deliberately limited to normal web destinations.
 * It cannot download, open a mail client, execute a script, or carry a
 * pseudo-checkout URL. Keeping the route explicit also makes every CTA
 * inspectable in the generated one-file page.
 */
function safeOutboundUrl(value?: string) {
  const candidate = value?.trim() ?? "";
  const hasControlCharacter = [...candidate].some((character) => {
    const code = character.charCodeAt(0);
    return code <= 31 || code === 127;
  });
  if (!candidate || hasControlCharacter) return null;

  try {
    const parsed = new URL(candidate);
    return parsed.protocol === "https:" || parsed.protocol === "http:" ? parsed.href : null;
  } catch {
    return null;
  }
}

function isLocalDevelopmentUrl(value: string | null) {
  if (!value) return false;

  try {
    const hostname = new URL(value).hostname.toLowerCase().replace(/^\[|\]$/g, "");
    return hostname === "localhost" || hostname === "::1" || hostname.startsWith("127.");
  } catch {
    return false;
  }
}

function formatListingPrice(price: number | string, currency: string, language: Language, priceOnRequest: string) {
  const normalizedCurrency = currency.trim().toUpperCase();
  if (typeof price === "number" && Number.isFinite(price)) {
    if (normalizedCurrency) {
      try {
        return new Intl.NumberFormat(localeByLanguage[language], {
          style: "currency",
          currency: normalizedCurrency,
          maximumFractionDigits: Number.isInteger(price) ? 0 : 2,
        }).format(price);
      } catch {
        return `${price.toLocaleString(localeByLanguage[language])} ${normalizedCurrency}`;
      }
    }

    return price.toLocaleString(localeByLanguage[language]);
  }

  const textPrice = String(price).trim();
  return textPrice ? [textPrice, normalizedCurrency].filter(Boolean).join(" ") : priceOnRequest;
}

function displayDomain(domain: string) {
  return domain.trim() || "yourdomain.com";
}

