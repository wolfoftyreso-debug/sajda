export default function SaleLandingGenerator({
  domain,
  price,
  currency,
  description,
  listingUrl,
  contactUrl,
  className,
}: SaleLandingGeneratorProps) {
  const { language } = useLanguage();
  const strings = saleLandingCopy[language];
  const [downloadStatus, setDownloadStatus] = useState("");
  const [copied, setCopied] = useState(false);
  const [configuredListingUrl, setConfiguredListingUrl] = useState(listingUrl);

  useEffect(() => {
    setConfiguredListingUrl(listingUrl);
  }, [listingUrl]);

  const resolvedDomain = displayDomain(domain);
  const resolvedDescription = description?.trim() || strings.defaultDescription;
  const resolvedPrice = useMemo(
    () => formatListingPrice(price, currency, language, strings.priceOnRequest),
    [currency, language, price, strings.priceOnRequest],
  );
  const resolvedListingUrl = useMemo(() => safeOutboundUrl(configuredListingUrl), [configuredListingUrl]);
  const resolvedContactUrl = useMemo(() => safeOutboundUrl(contactUrl), [contactUrl]);
  const listingUrlIsLocal = isLocalDevelopmentUrl(resolvedListingUrl);
  const isListingDeployable = Boolean(resolvedListingUrl && !listingUrlIsLocal);
  const downloadDocument = useMemo(
    () => createSaleLandingHtml({
      domain: resolvedDomain,
      price: resolvedPrice,
      description: resolvedDescription,
      listingUrl: isListingDeployable ? resolvedListingUrl : null,
      contactUrl: resolvedContactUrl,
      language,
    }),
    [isListingDeployable, language, resolvedContactUrl, resolvedDescription, resolvedDomain, resolvedListingUrl, resolvedPrice],
  );

  const handleDownload = () => {
    const blob = new Blob([downloadDocument], { type: "text/html;charset=utf-8" });
    const objectUrl = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = objectUrl;
    anchor.download = "index.html";
    anchor.style.display = "none";
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    window.setTimeout(() => URL.revokeObjectURL(objectUrl), 0);
    setDownloadStatus(strings.downloaded);
  };

  const handleCopyLink = async () => {
    if (!isListingDeployable || !resolvedListingUrl) return;

    try {
      await navigator.clipboard.writeText(resolvedListingUrl);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      window.prompt(strings.listingLink, resolvedListingUrl);
    }
  };

  return (
    <section className={cn("overflow-hidden rounded-3xl border border-border bg-card shadow-sm", className)} aria-labelledby="sale-landing-generator-title">
      <div className="flex flex-col gap-4 border-b border-border/80 bg-gradient-to-r from-primary/[0.06] via-card to-card px-5 py-5 sm:flex-row sm:items-start sm:justify-between sm:px-7">
        <div className="min-w-0">
          <div className="flex items-center gap-2 text-xs font-semibold uppercase tracking-[0.14em] text-primary">
            <FileCode2 className="h-4 w-4" aria-hidden="true" />
            {strings.eyebrow}
          </div>
          <h2 id="sale-landing-generator-title" className="mt-2 text-xl font-semibold tracking-tight text-foreground sm:text-2xl">
            {strings.title}
          </h2>
          <p className="mt-2 max-w-2xl text-sm leading-6 text-muted-foreground">{strings.body}</p>
        </div>
        <span className="inline-flex w-fit shrink-0 items-center gap-2 rounded-full border border-primary/15 bg-card px-3 py-1.5 text-xs font-semibold text-primary shadow-sm">
          <FileCode2 className="h-3.5 w-3.5" aria-hidden="true" />
          {strings.ready}
        </span>
      </div>

      <div className="grid gap-5 p-5 lg:grid-cols-[minmax(0,1fr)_minmax(18rem,0.52fr)] lg:gap-7 lg:p-7">
        <div>
          <div className="mb-3 flex items-center justify-between gap-3">
            <p className="text-sm font-semibold text-foreground">{strings.preview}</p>
            <span className="rounded-full border border-border bg-card px-2.5 py-1 text-[0.68rem] font-semibold uppercase tracking-[0.11em] text-muted-foreground">index.html</span>
          </div>

          <div className="overflow-hidden rounded-2xl border border-border bg-[radial-gradient(circle_at_88%_8%,hsl(var(--primary)/0.10),transparent_13rem),#f5f8fc] p-3 sm:p-5">
            <div className="relative overflow-hidden rounded-xl border border-border/85 bg-card p-5 shadow-[0_16px_38px_rgba(29,48,79,0.08)] sm:p-7">
              <div className="pointer-events-none absolute -right-12 -top-16 h-40 w-40 rounded-full border border-primary/20 bg-primary/[0.04]" aria-hidden="true" />
              <div className="relative flex items-center justify-between gap-3">
                <div className="flex items-center gap-2.5 text-sm font-semibold tracking-tight text-foreground">
                  <span className="grid h-8 w-8 place-items-center rounded-lg bg-primary text-sm font-bold italic text-primary-foreground shadow-sm" aria-hidden="true">S</span>
                  sajda
                </div>
                <span className="inline-flex items-center gap-1.5 text-[0.65rem] font-semibold uppercase tracking-[0.12em] text-muted-foreground">
                  <span className="h-1.5 w-1.5 rounded-full bg-emerald-500 ring-4 ring-emerald-500/10" aria-hidden="true" />
                  {strings.documentEyebrow}
                </span>
              </div>

              <div className="relative mt-10 max-w-xl">
                <h3 className="break-words text-4xl font-semibold tracking-[-0.06em] text-foreground sm:text-5xl">{resolvedDomain}</h3>
                <p className="mt-3 text-base leading-7 text-muted-foreground">{strings.documentAvailable}</p>
              </div>

              <div className="relative mt-7 grid gap-3 border-t border-border pt-6 sm:grid-cols-[0.82fr_1.18fr]">
                <div className="rounded-xl border border-border bg-muted/[0.34] p-4">
                  <p className="text-[0.67rem] font-semibold uppercase tracking-[0.11em] text-muted-foreground">{strings.price}</p>
                  <p className="mt-2 text-2xl font-semibold tracking-[-0.045em] text-foreground">{resolvedPrice}</p>
                </div>
                <div className="rounded-xl border border-border bg-muted/[0.2] p-4">
                  <p className="text-[0.67rem] font-semibold uppercase tracking-[0.11em] text-muted-foreground">{strings.documentProfile}</p>
                  <p className="mt-2 whitespace-pre-line text-sm leading-6 text-muted-foreground">{resolvedDescription}</p>
                </div>
              </div>

              <div className="relative mt-6 flex flex-wrap items-center gap-3">
                {isListingDeployable && resolvedListingUrl ? (
                  <a
                    href={resolvedListingUrl}
                    target="_blank"
                    rel="noreferrer"
                    className="inline-flex min-h-11 items-center gap-2 rounded-xl bg-primary px-4 text-sm font-semibold text-primary-foreground shadow-sm transition-colors hover:bg-primary/90 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2"
                  >
                    {strings.documentDirect}
                    <ArrowUpRight className="h-4 w-4" aria-hidden="true" />
                  </a>
                ) : (
                  <span className="inline-flex min-h-11 cursor-not-allowed items-center gap-2 rounded-xl bg-muted px-4 text-sm font-semibold text-muted-foreground" aria-disabled="true">
                    {strings.documentDirect}
                    <ExternalLink className="h-4 w-4" aria-hidden="true" />
                  </span>
                )}
                {resolvedContactUrl ? (
                  <a
                    href={resolvedContactUrl}
                    target="_blank"
                    rel="noreferrer"
                    className="inline-flex min-h-11 items-center gap-2 rounded-xl border border-primary/20 bg-primary/[0.06] px-4 text-sm font-semibold text-primary transition-colors hover:bg-primary/[0.11] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2"
                  >
                    {strings.documentOffer}
                    <ArrowUpRight className="h-4 w-4" aria-hidden="true" />
                  </a>
                ) : null}
              </div>
              <p className="relative mt-4 text-xs leading-5 text-muted-foreground">{resolvedContactUrl ? strings.documentRoute : strings.documentNoOffer}</p>
            </div>
          </div>
        </div>

        <aside className="flex flex-col rounded-2xl border border-border bg-muted/[0.35] p-5 sm:p-6">
          <div className="flex items-start gap-3">
            <span className="grid h-10 w-10 shrink-0 place-items-center rounded-xl bg-card text-primary shadow-sm ring-1 ring-border/80">
              <Link2 className="h-4.5 w-4.5" aria-hidden="true" />
            </span>
            <div>
              <p className="text-sm font-semibold text-foreground">{strings.listingLink}</p>
              <p className="mt-1 text-sm leading-6 text-muted-foreground">{strings.previewNote}</p>
            </div>
          </div>

          <div className={cn(
            "mt-5 rounded-xl border px-3.5 py-3 text-sm leading-5",
            isListingDeployable ? "border-emerald-200 bg-emerald-50 text-emerald-900" : "border-amber-200 bg-amber-50 text-amber-900",
          )}>
            <div className="flex gap-2">
              <ShieldCheck className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
              <span>{isListingDeployable ? strings.validLink : listingUrlIsLocal ? strings.localLink : strings.invalidLink}</span>
            </div>
          </div>

          <label className="mt-5 block">
            <span className="text-sm font-semibold text-foreground">{strings.publicListingUrl}</span>
            <input
              type="url"
              value={configuredListingUrl}
              onChange={(event) => setConfiguredListingUrl(event.target.value)}
              placeholder="https://sajda.dev/marketplace/..."
              autoComplete="url"
              spellCheck={false}
              className="mt-2 h-11 w-full rounded-xl border border-input bg-background px-3 text-sm text-foreground outline-none transition-colors placeholder:text-muted-foreground focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2"
            />
            <span className="mt-2 block text-xs leading-5 text-muted-foreground">{listingUrlIsLocal ? strings.localLinkHint : strings.publicListingHint}</span>
          </label>

          {isListingDeployable && resolvedListingUrl ? (
            <Button type="button" variant="outline" onClick={handleCopyLink} className="mt-3 w-full">
              {copied ? <Check className="h-4 w-4" aria-hidden="true" /> : <Copy className="h-4 w-4" aria-hidden="true" />}
              {copied ? strings.copied : strings.copyLink}
            </Button>
          ) : null}

          <div className="mt-5 border-t border-border pt-5">
            <p className="text-sm font-semibold text-foreground">{strings.contactLink}</p>
            <p className="mt-1 text-sm leading-6 text-muted-foreground">{resolvedContactUrl ? strings.contactReady : strings.contactMissing}</p>
          </div>

          <div className="mt-5 rounded-xl border border-border bg-card p-4">
            <p className="text-sm font-semibold text-foreground">{strings.deployTitle}</p>
            <p className="mt-1 text-sm leading-6 text-muted-foreground">{strings.deployBody}</p>
            <ol className="mt-4 space-y-2 text-xs leading-5 text-muted-foreground">
              {[strings.deployStepOne, strings.deployStepTwo, strings.deployStepThree].map((step, index) => (
                <li key={step} className="flex gap-2">
                  <span className="grid h-5 w-5 shrink-0 place-items-center rounded-full bg-primary/[0.08] text-[0.65rem] font-semibold text-primary">{index + 1}</span>
                  <span>{step}</span>
                </li>
              ))}
            </ol>
          </div>

          <p className="mt-5 text-sm leading-6 text-muted-foreground">{strings.disclosure}</p>

          <div className="mt-auto pt-6">
            <Button type="button" onClick={handleDownload} className="w-full" disabled={!isListingDeployable}>
              <Download className="h-4 w-4" aria-hidden="true" />
              {strings.download}
            </Button>
            <p className="mt-3 text-center text-xs leading-5 text-muted-foreground">{strings.downloadHint}</p>
            <p className="sr-only" aria-live="polite" role="status">{downloadStatus}</p>
          </div>
        </aside>
      </div>
    </section>
  );
}
